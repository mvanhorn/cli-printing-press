func TestBothSidesConflictRefusesApplyUnlessAcknowledged(t *testing.T) {
	t.Parallel()

	rel := filepath.Join("internal", "cli", "root.go")
	baseSrc := bothSidesHeader + `func preRun(f *flags) {
	f.mode = "base"
}
func other() string { return "orig" }
`
	pubSrc := bothSidesHeader + `func preRun(f *flags) {
	f.mode = "hand"
}
func other() string { return "kept" }
`
	freshSrc := bothSidesHeader + `func preRun(f *flags) {
	f.mode = "template"
}
func other() string { return "orig" }
`
	baseDir, pubDir, freshDir := writeBothSidesTrees(t, rel, baseSrc, pubSrc, freshSrc)
	before := readFileString(t, filepath.Join(pubDir, rel))
	report := classifyBothSides(t, pubDir, freshDir, baseDir)
	fc := fileClass(t, report, rel)
	require.NotNil(t, fc.BothSides)
	require.Len(t, fc.BothSides.Conflicts, 1)
	assert.Equal(t, "preRun", fc.BothSides.Conflicts[0].Name)
	assert.Contains(t, fc.BothSides.Conflicts[0].Base, "base")
	assert.Contains(t, fc.BothSides.Conflicts[0].Fresh, "template")
	assert.Contains(t, fc.BothSides.Conflicts[0].Published, "hand")
	assert.Empty(t, fc.BothSides.Merged)

	err := Apply(report, Options{Force: true, BaseDir: baseDir})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "preRun")
	assert.Contains(t, err.Error(), "--allow-decl-conflicts")
	assert.Equal(t, before, readFileString(t, filepath.Join(pubDir, rel)))

	require.NoError(t, Apply(report, Options{Force: true, BaseDir: baseDir, AllowDeclConflicts: true}))
	got := readFileString(t, filepath.Join(pubDir, rel))
	assert.Contains(t, got, `f.mode = "template"`)
	assert.NotContains(t, got, `f.mode = "hand"`)
	assert.Contains(t, got, `return "kept"`)
}

