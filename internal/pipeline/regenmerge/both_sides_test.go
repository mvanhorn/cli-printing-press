func writeBothSidesTrees(t *testing.T, rel, baseSrc, pubSrc, freshSrc string) (string, string, string) {
	t.Helper()
	root := t.TempDir()
	baseDir := filepath.Join(root, "base")
	pubDir := filepath.Join(root, "published")
	freshDir := filepath.Join(root, "fresh")
	for _, pair := range []struct {
		dir, src string
	}{
		{baseDir, baseSrc},
		{pubDir, pubSrc},
		{freshDir, freshSrc},
	} {
		full := filepath.Join(pair.dir, rel)
		require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
		require.NoError(t, os.WriteFile(full, []byte(pair.src), 0o644))
	}
	return baseDir, pubDir, freshDir
}

func classifyBothSides(t *testing.T, pubDir, freshDir, baseDir string) *MergeReport {
	t.Helper()
	report, err := Classify(pubDir, freshDir, Options{Force: true, BaseDir: baseDir})
	require.NoError(t, err)
	return report
}

func fileClass(t *testing.T, report *MergeReport, rel string) FileClassification {
	t.Helper()
	rel = filepath.ToSlash(rel)
	for _, fc := range report.Files {
		if fc.Path == rel {
			return fc
		}
	}
	t.Fatalf("missing classification for %s", rel)
	return FileClassification{}
}
