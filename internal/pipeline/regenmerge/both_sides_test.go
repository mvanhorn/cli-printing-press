func TestMerge3KeepsNonOverlappingEdits(t *testing.T) {
	t.Parallel()

	base := "func preRun(f *flags) {\n\tif f.agent {\n\t\tf.yes = true\n\t\tf.json = true\n\t}\n}"
	published := "func preRun(f *flags) {\n\tif f.agent {\n\t\tf.yes = true\n\t\tf.json = true\n\t}\n\tf.handAdded = true\n}"
	fresh := "func preRun(f *flags) {\n\tif f.agent {\n\t\tf.json = true\n\t}\n}"
	got, _, ok := merge3(base, published, fresh)
	require.True(t, ok)
	assert.Contains(t, got, "f.handAdded = true")
	assert.NotContains(t, got, "f.yes = true")
	assert.Contains(t, got, "f.json = true")
}

func TestMerge3ConflictsWhenTheSameLineChanges(t *testing.T) {
	t.Parallel()

	base := "func preRun(f *flags) {\n\tf.mode = \"base\"\n}"
	published := "func preRun(f *flags) {\n\tf.mode = \"hand\"\n}"
	fresh := "func preRun(f *flags) {\n\tf.mode = \"template\"\n}"
	_, hunk, ok := merge3(base, published, fresh)
	require.False(t, ok)
	assert.Contains(t, hunk.ours, "hand")
	assert.Contains(t, hunk.theirs, "template")
	assert.Contains(t, hunk.base, "base")
}

